#!/usr/bin/env node
// ===================== Creator Reps: site generator =====================
// Reads content/*.md (9 fixed lesson sections + course-overview + video-picks)
// and writes the static site under site/. Re-run any time content changes:
//   node generate.mjs            (all 8 tracks)
//   node generate.mjs --only=scriptwriting   (one track, for fast iteration)
//
// Does NOT touch assets/styles.css or assets/progress.js -- those are the
// hand-authored design system, edited directly, same as before this rebuild.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parseTrackOverview, parseLesson, parseVideoPicks } from './lib.mjs';
import { renderTrackDashboard, renderLessonPage, renderRedirectStub, renderHub } from './templates.mjs';

// Interactive demo content: one data module per track in build/demos-data/.
// Missing folder or files are fine; lessons without a demo entry keep their
// video pick or honest gap note.
async function loadDemosData() {
  const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'demos-data');
  const byTrack = new Map();
  if (!fs.existsSync(dir)) return byTrack;
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.mjs'))) {
    try {
      const mod = await import(`./demos-data/${f}`);
      const data = mod.default;
      if (data && data.track && data.demos) byTrack.set(data.track, data.demos);
    } catch (e) {
      console.error(`demos-data/${f} failed to load: ${e.message}`);
      process.exitCode = 1;
    }
  }
  return byTrack;
}
const DEMOS_BY_TRACK = await loadDemosData();

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = path.resolve(__dirname, '..');
const CONTENT_ROOT = path.resolve(__dirname, '../../content');

const TRACK_DEFS = [
  { slug: 'smartphone', dir: CONTENT_ROOT },
  { slug: 'pro-camera', dir: path.join(CONTENT_ROOT, 'pro-camera') },
  { slug: 'ai-creator', dir: path.join(CONTENT_ROOT, 'ai-creator') },
  { slug: 'weekend-youtuber', dir: path.join(CONTENT_ROOT, 'weekend-youtuber') },
  { slug: 'short-form', dir: path.join(CONTENT_ROOT, 'short-form') },
  { slug: 'course-creator', dir: path.join(CONTENT_ROOT, 'course-creator') },
  { slug: 'content-strategist', dir: path.join(CONTENT_ROOT, 'content-strategist') },
  { slug: 'scriptwriting', dir: path.join(CONTENT_ROOT, 'scriptwriting') },
];

const onlyArg = process.argv.find((a) => a.startsWith('--only='));
const onlySlugs = onlyArg ? onlyArg.replace('--only=', '').split(',') : null;

function readFile(p) {
  return fs.readFileSync(p, 'utf8');
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function listLessonFiles(dir) {
  return fs.readdirSync(dir)
    .filter((f) => /^lesson-\d+\.md$/.test(f))
    .map((f) => ({ file: f, n: parseInt(f.match(/^lesson-(\d+)\.md$/)[1], 10) }))
    .sort((a, b) => a.n - b.n);
}

function buildTrack(def) {
  const overviewMd = readFile(path.join(def.dir, 'course-overview.md'));
  const overview = parseTrackOverview(overviewMd, def.slug);

  const videoPicksPath = path.join(def.dir, 'video-picks.md');
  const videoPicks = fs.existsSync(videoPicksPath) ? parseVideoPicks(readFile(videoPicksPath)) : new Map();

  const lessonFiles = listLessonFiles(def.dir);
  const lessons = lessonFiles.map(({ file, n }) => parseLesson(readFile(path.join(def.dir, file)), n));

  // Group lessons into modules using each lesson's own **Module:** line (authoritative),
  // matching names/descriptions against the overview's module bullets by module number.
  const moduleOrder = [];
  const moduleMap = new Map();
  lessons.forEach((l) => {
    if (!moduleMap.has(l.moduleNum)) {
      moduleMap.set(l.moduleNum, { n: l.moduleNum, name: l.moduleName, lessons: [] });
      moduleOrder.push(l.moduleNum);
    }
    moduleMap.get(l.moduleNum).lessons.push(l.n);
  });
  const modules = moduleOrder.map((n) => moduleMap.get(n));

  const itemCounts = {};
  lessons.forEach((l) => { itemCounts[l.n] = l.checklist.length; });

  return {
    slug: def.slug,
    title: overview.trackTitle,
    tagline: overview.tagline,
    taglineFull: overview.taglineFull,
    howto: overview.howto,
    modules,
    lessons,
    totalLessons: lessons.length,
    itemCounts,
    videoPicks,
  };
}

function buildTracksDataRegistry(tracks) {
  const registry = {};
  tracks.forEach((t) => {
    registry[t.slug] = {
      name: t.title,
      slug: t.slug,
      totalLessons: t.totalLessons,
      itemCounts: t.itemCounts,
      modules: t.modules.map((m) => ({ n: m.n, name: m.name, lessons: m.lessons })),
      lessons: t.lessons.map((l) => ({ n: l.n, title: l.title, module: l.moduleNum })),
    };
  });
  return registry;
}

function writeTracksDataJs(registry) {
  const out = `// GENERATED by site/build/generate.mjs -- do not hand-edit.
// Registry of every track's lesson/module structure + checklist item counts,
// used by assets/progress.js to compute per-track and academy-wide progress.
window.SF_TRACKS = ${JSON.stringify(registry, null, 2)};
`;
  fs.writeFileSync(path.join(SITE_ROOT, 'assets', 'tracks-data.js'), out, 'utf8');
}

function writeTrack(track) {
  const trackDir = path.join(SITE_ROOT, track.slug);
  ensureDir(trackDir);

  fs.writeFileSync(path.join(trackDir, 'index.html'), renderTrackDashboard(track), 'utf8');

  const trackDemos = DEMOS_BY_TRACK.get(track.slug) || {};
  track.lessons.forEach((lesson, i) => {
    const prev = track.lessons[i - 1] || null;
    const next = track.lessons[i + 1] || null;
    const nn = String(lesson.n).padStart(2, '0');
    const demo = trackDemos[`lesson-${nn}`] || null;
    fs.writeFileSync(path.join(trackDir, `lesson-${nn}.html`), renderLessonPage(track, lesson, prev, next, demo), 'utf8');
  });
}

function writeSmartphoneRedirectStubs(track) {
  track.lessons.forEach((lesson) => {
    const nn = String(lesson.n).padStart(2, '0');
    const target = `smartphone/lesson-${nn}.html`;
    fs.writeFileSync(
      path.join(SITE_ROOT, `lesson-${nn}.html`),
      renderRedirectStub(target, `Lesson ${lesson.n}: ${lesson.title}`),
      'utf8'
    );
  });
}

function main() {
  ensureDir(path.join(SITE_ROOT, 'assets'));

  const defs = onlySlugs ? TRACK_DEFS.filter((d) => onlySlugs.includes(d.slug)) : TRACK_DEFS;
  const tracks = defs.map(buildTrack);

  tracks.forEach(writeTrack);

  const smartphoneTrack = tracks.find((t) => t.slug === 'smartphone');
  if (smartphoneTrack) writeSmartphoneRedirectStubs(smartphoneTrack);

  // The hub and the shared tracks-data.js need every track's data, even on a
  // --only run, so a partial build never breaks the academy-wide totals.
  const allTracks = onlySlugs
    ? TRACK_DEFS.map((d) => (defs.includes(d) ? tracks[defs.indexOf(d)] : buildTrack(d)))
    : tracks;

  writeTracksDataJs(buildTracksDataRegistry(allTracks));
  fs.writeFileSync(path.join(SITE_ROOT, 'index.html'), renderHub(allTracks), 'utf8');

  const summary = tracks.map((t) => `  ${t.slug.padEnd(20)} ${t.totalLessons} lessons, ${t.modules.length} modules`).join('\n');
  console.log(`Generated ${tracks.length} track(s):\n${summary}`);
  console.log(`Hub + tracks-data.js reflect all ${allTracks.length} tracks (${allTracks.reduce((s, t) => s + t.totalLessons, 0)} lessons total).`);
}

main();
